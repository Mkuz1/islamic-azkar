private val AR_DIGITS = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')

/** Formats a number with Arabic-Indic digits when the language is Arabic. */
fun Lang.num(n: Int): String = if (this != Lang.AR) n.toString() else buildString {
    for (ch in n.toString()) append(if (ch in '0'..'9') AR_DIGITS[ch - '0'] else ch)
}

fun Lang.clock(minutes: Int): String {
    val h = minutes / 60
    val m = minutes % 60
    return num(h).padStart(2, if (this == Lang.AR) '٠' else '0') + ":" + num(m).padStart(2, if (this == Lang.AR) '٠' else '0')
}

